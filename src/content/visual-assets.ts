const illustration = (slug: string, subject: string, alt: string): VisualAssetInput => ({
  id: `ill-${slug}`,
  kind: "illustration",
  status: "available",
  file: `/symptoms/illustrations/${slug}.svg`,
  width: 480,
  height: 360,
  alt,
  subject,
  ...ORIGINAL,
});

