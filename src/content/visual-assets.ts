/**
 * The asset manifest for the visual symptom library: every image the site can
 * show, what it depicts, and where it came from.
 *
 * Illustrations are original drawings made for FixMyPrint by
 * scripts/illustrations/generate.py. Photographs are listed as "missing" until a
 * properly licensed photo of the real defect has been obtained; add the file to
 * public/symptoms/photos and fill in creator, licence, source and attribution to
 * use it. The interface shows the first available image for each symptom.
 */

